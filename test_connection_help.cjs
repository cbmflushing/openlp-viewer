// Real-browser regression checks: node test_connection_help.cjs [path-to-chrome]
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const {spawn} = require('node:child_process');
const {pathToFileURL} = require('node:url');
const chromePath = process.argv[2] || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const source = fs.readFileSync(path.join(__dirname, 'lyrics-display.html'), 'utf8');
const setup = `<script>
localStorage.setItem('cbmDisplaySettings', JSON.stringify({firstRun:false}));
window.WebSocket = undefined;
window.testNetwork = {mode:'fail', calls:0, pending:[]};
window.fetch = async () => {
    testNetwork.calls++;
    if (testNetwork.mode === 'pending') return new Promise(resolve => testNetwork.pending.push(resolve));
    if (testNetwork.mode === 'fail') throw new Error('offline');
    return {ok:true,json:async()=>testNetwork.mode === 'empty' ? {results:{slides:[]}} : {results:{slides:[{selected:true,text:testNetwork.mode === 'invalid' ? {} : 'Amazing grace'}]}}};
};
window.setInterval = fn => { window.testPoll = fn; return 1; };
window.clearInterval = () => {};
</script>`;
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lyrics-help-'));
const file = path.join(dir, 'viewer.html');
fs.writeFileSync(file, source.replace('<head>', '<head>'+setup));
const profile = path.join(dir, 'profile');
const chrome = spawn(chromePath, ['--headless','--no-sandbox','--disable-gpu','--remote-debugging-port=0','--user-data-dir='+profile,'about:blank'], {stdio:'ignore'});
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
 try {
  const portFile = path.join(profile, 'DevToolsActivePort');
  for (let i=0;i<100&&!fs.existsSync(portFile);i++) await sleep(100);
  if (!fs.existsSync(portFile)) throw Error('Chrome did not start');
  const port = fs.readFileSync(portFile,'utf8').split('\n')[0];
  const tabs = await (await fetch('http://127.0.0.1:'+port+'/json')).json();
  const ws = new WebSocket(tabs[0].webSocketDebuggerUrl);
  await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject});
  let id=0; const pending=new Map();
  ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.id&&pending.has(m.id)){const [resolve,reject]=pending.get(m.id);pending.delete(m.id);m.error?reject(Error(JSON.stringify(m.error))):resolve(m.result)}};
  const send=(method,params={})=>new Promise((resolve,reject)=>{const n=++id;pending.set(n,[resolve,reject]);ws.send(JSON.stringify({id:n,method,params}))});
  const evaluate=async expression=>{const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value};
  const run=async expression=>{await evaluate(expression);await sleep(30)};
  const visible=selector=>evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)return false;const s=getComputedStyle(e),r=e.getBoundingClientRect();return s.display!=='none' && s.visibility!=='hidden' && r.width>0 && r.height>0})()`);
  const project='#connection-help';
  const settings='#settings-connection-help';
  const styleFailures=[];
  const checkStyle=(condition,message)=>{if(!condition) styleFailures.push(message)};
  const style=selector=>evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)}),s=getComputedStyle(e),r=e.getBoundingClientRect();return {background:s.backgroundColor,color:s.color,border:s.borderTopWidth,borderColor:s.borderTopColor,radii:[s.borderTopLeftRadius,s.borderTopRightRadius,s.borderBottomRightRadius,s.borderBottomLeftRadius],shadow:s.boxShadow,outline:s.outlineStyle,outlineWidth:s.outlineWidth,outlineColor:s.outlineColor,transform:s.transform,width:r.width,height:r.height}})()`);
  const checkCard=(s,name)=>{
   checkStyle(s.background==='rgb(250, 247, 239)',name+' warm paper surface');
   checkStyle(s.color==='rgb(48, 45, 53)',name+' readable dark text');
   checkStyle(s.border==='2px' && s.borderColor==='rgb(57, 52, 59)',name+' dark outline');
   checkStyle(new Set(s.radii).size>1,name+' irregular corners');
   checkStyle(s.shadow!=='none',name+' offset shadow');
  };
  const screenshot=async name=>{
   if(!process.env.CONNECTION_HELP_SCREENSHOTS) return;
   const result=await send('Page.captureScreenshot',{format:'png'});
   fs.writeFileSync(path.join(__dirname,'.scratch/viewer-distribution-and-connection-help/evidence',name),Buffer.from(result.data,'base64'));
  };
  await send('Page.enable');
  await send('Page.navigate',{url:pathToFileURL(file).href}); await sleep(200);
  assert.equal(await evaluate('testNetwork.calls'), 1);
  for(let i=0;i<3;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'no projected help before fifth failed request');
  await run(`testNetwork.mode='pending';testPoll()`);
  const callsInFlight=await evaluate('testNetwork.calls');
  for(let i=0;i<8;i++) await run('testPoll()');
  assert.equal(await evaluate('testNetwork.calls'),callsInFlight,'poll ticks do not count while request is in flight');
  assert.equal(await visible(project),false);
  await run(`testNetwork.pending.shift()({ok:false})`);
  assert.equal(await visible(project),true,'fifth failure shows projected help above fade');
  await run(`testNetwork.mode='fail'`);
  assert.equal(await evaluate(`(()=>{const e=document.querySelector('${project}'),r=e.getBoundingClientRect();return document.elementFromPoint(r.left+r.width/2,r.top+r.height/2).closest('${project}')!==null})()`),true,'help is not hidden behind fade');
  const helpText=await evaluate(`document.querySelector('${project}').textContent`);
  assert.match(helpText,/OpenLP.*running/i); assert.match(helpText,/remote server.*enabled/i); assert.match(helpText,/server address.*Settings/i);
  checkCard(await style(project),'projected card');
  const button=project+' button';
  const normal=await style(button);
  checkStyle(normal.background==='rgb(216, 208, 237)' && normal.color==='rgb(48, 45, 53)','button muted purple with dark text');
  checkStyle(normal.border==='2px' && normal.borderColor==='rgb(57, 52, 59)' && new Set(normal.radii).size>1 && normal.shadow!=='none','button sketch outline and shadow');
  checkStyle(normal.width>=44 && normal.height>=44,'button meets 44px target');
  await send('Input.dispatchKeyEvent',{type:'keyDown',key:'Tab',code:'Tab',windowsVirtualKeyCode:9});
  await send('Input.dispatchKeyEvent',{type:'keyUp',key:'Tab',code:'Tab',windowsVirtualKeyCode:9});
  const focused=await style(button);
  checkStyle(await evaluate(`document.activeElement===document.querySelector('${button}')`) && focused.outline!=='none' && parseFloat(focused.outlineWidth)>=3 && focused.outlineColor==='rgb(101, 84, 164)','button visible keyboard focus');
  await screenshot('refined-projected-notice.png');
  const point=await evaluate(`(()=>{const r=document.querySelector('${button}').getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`);
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',...point});
  const hovered=await style(button);
  checkStyle(hovered.background!==normal.background,'button visible hover');
  await send('Input.dispatchMouseEvent',{type:'mousePressed',button:'left',clickCount:1,...point});
  const active=await style(button);
  checkStyle(active.shadow!==hovered.shadow && active.transform!=='none','button visible active press');
  await send('Input.dispatchMouseEvent',{type:'mouseReleased',button:'left',clickCount:1,x:0,y:0});
  await run(`document.querySelector('${project} button').click()`);
  assert.equal(await evaluate(`!document.querySelector('#modal-overlay').classList.contains('hidden')`),true,'projected button opens settings');
  assert.equal(await visible(settings),true,'notice also available in settings');
  checkCard(await style(settings),'settings notice');
  await screenshot('refined-settings-notice.png');
  await run('closeModal(false)');
  await send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
  for(const width of [320,375]) {
   await send('Emulation.setDeviceMetricsOverride',{width,height:667,deviceScaleFactor:1,mobile:true});
   const layout=await evaluate(`(()=>{const card=document.querySelector('${project}'),button=card.querySelector('button'),c=card.getBoundingClientRect(),b=button.getBoundingClientRect();return {coarse:matchMedia('(pointer: coarse)').matches,cardFits:c.left>=0 && c.right<=innerWidth && c.top>=0 && c.bottom<=innerHeight && card.scrollWidth<=card.clientWidth,buttonFits:b.left>=c.left && b.right<=c.right && b.width>=44 && b.height>=44}})()`);
   checkStyle(layout.coarse && layout.cardFits && layout.buttonFits,width+'px touch projected card and button fit');
   await run('showSettings()');
   const settingsFit=await evaluate(`(()=>{const modal=document.querySelector('#modal'),notice=document.querySelector('${settings}'),m=modal.getBoundingClientRect(),n=notice.getBoundingClientRect();return m.left>=0 && m.right<=innerWidth && modal.scrollWidth<=modal.clientWidth && n.left>=m.left && n.right<=m.right && notice.scrollWidth<=notice.clientWidth})()`);
   checkStyle(settingsFit,width+'px settings notice fits without horizontal overflow');
   await run('closeModal(false)');
  }
  await send('Emulation.setTouchEmulationEnabled',{enabled:false});
  await send('Emulation.clearDeviceMetricsOverride');
  assert.deepEqual(styleFailures,[],'connection help sketch styling: '+styleFailures.join('; '));
  await run(`testNetwork.mode='empty';testPoll()`);
  assert.equal(await visible(project),false,'empty success clears help');
  assert.equal(await evaluate(`document.querySelector('#fade-overlay').classList.contains('dark')`),true,'empty success keeps fade');
  await run(`testNetwork.mode='fail';testPoll()`);
  for(let i=0;i<3;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'success resets failure count');
  await run('testPoll()');
  assert.equal(await visible(project),true);
  await run(`testNetwork.mode='lyrics';testPoll()`);
  assert.equal(await visible(project),false,'lyrics success clears help');
  const projected=await evaluate(`document.querySelector('#content').innerHTML`);
  assert.match(projected,/Amazing grace/);
  await run(`testNetwork.mode='fail';testPoll()`);
  for(let i=0;i<4;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'after lyrics no projected help');
  assert.equal(await evaluate(`document.querySelector('#content').innerHTML`),projected,'lyrics preserved during failures');
  assert.equal(await evaluate(`document.querySelector('#fade-overlay').classList.contains('dark')`),false,'failures do not fade lyrics');
  await run('showSettings()');
  assert.equal(await visible(settings),true,'after lyrics help is inside settings');
  await run(`testNetwork.mode='empty';testPoll()`);
  assert.equal(await visible(settings),false,'empty success clears settings notice');
  await run('closeModal(false)');
  await run(`testNetwork.mode='fail';testPoll()`);
  for(let i=0;i<4;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'empty success does not forget previously loaded lyrics');
  await run('showSettings()');
  assert.equal(await visible(settings),true);
  // A same-server save does not replace the lifetime; reset does.
  await run('closeModal(true)');
  await run('showSettings()');
  assert.equal(await visible(settings),true,'same-server save retains state');
  await run(`testNetwork.mode='pending';testPoll()`);
  await run('resetSettings()');
  assert.equal(await visible(settings),false,'reset clears help');
  await run(`testNetwork.pending[0]({ok:true,json:async()=>({results:{slides:[{selected:true,text:'Stale'}]}})})`);
  await run('closeModal(false)');
  // Complete the new connection's pending initial request as a failure.
  await run(`testNetwork.pending[1]({ok:false})`);
  await run(`testNetwork.mode='fail';testPoll()`);
  for(let i=0;i<2;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'replacement resets count');
  await run('testPoll()');
  assert.equal(await visible(project),true,'replacement forgets prior lyrics; stale success ignored');
  const calls=await evaluate('testNetwork.calls');
  await run('testPoll()');
  assert.equal(await evaluate('testNetwork.calls'),calls+1,'retries continue with help shown');
  await run(`document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'.',bubbles:true}))`);
  assert.equal(await visible(project),false,'local blackout hides projected help');
  await run(`document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'.',bubbles:true}))`);
  // A changed server starts a fresh lifetime and ignores a late old failure.
  await run(`testNetwork.mode='pending';testPoll()`);
  await run(`showSettings();document.querySelector('#server-ip').value='new.example:4316';closeModal(true)`);
  assert.equal(await visible(project),false,'changing server clears projected notice');
  await run(`testNetwork.pending[2]({ok:false})`);
  await run(`testNetwork.pending[3]({ok:false})`);
  await run(`testNetwork.mode='fail';testPoll()`);
  for(let i=0;i<2;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'stale failure did not count in replacement lifetime');
  await run('testPoll()');
  assert.equal(await visible(project),true,'changed server shows help on its fifth failure');
  await run(`testNetwork.mode='invalid';testPoll()`);
  for(let i=0;i<5;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'presentation errors on successful responses are not failed requests');
  await run(`testNetwork.mode='fail';testPoll()`);
  for(let i=0;i<3;i++) await run('testPoll()');
  assert.equal(await visible(project),false,'presentation errors do not accumulate toward threshold');
  await run('testPoll()');
  assert.equal(await visible(project),true);
  ws.close();
  console.log('Connection help browser checks passed');
 } finally {chrome.kill();await sleep(300);fs.rmSync(dir,{recursive:true,force:true});}
})().catch(e=>{console.error(e.stack);process.exitCode=1});
